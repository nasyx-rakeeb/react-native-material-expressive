import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(fileURLToPath(new URL('../../..', import.meta.url)));
const typographySourcePath = path.join(
  root,
  'tools/extract-tokens/vendor/extracted/material3-1.5.0/commonMain/androidx/compose/material3/tokens/TypographyTokens.kt',
);
const typographySpecPath = path.join(root, 'docs/specs/typography.json');
const outputPath = path.join(root, 'docs/research/DAY2_COMPOSITES.md');

interface RoleRecord {
  role: string;
  fontFamily: string;
  fontWeight: number;
  fontSize: number;
  lineHeight: number;
  letterSpacing: number;
  sources: Record<string, string>;
}

interface TypographySpec {
  artifact: string;
  jarSha256: string;
  defaults: {
    lineHeightStyle: { alignment: string; trim: string; source: string; sourceSha256: string };
    platformStyle: {
      includeFontPadding: boolean;
      expression: string;
      source: string;
      sourceSha256: string;
    };
  };
  roles: RoleRecord[];
}

interface Declaration {
  name: string;
  line: number;
  fields: Record<string, string>;
}

function camelCase(value: string): string {
  return `${value[0]?.toLowerCase() ?? ''}${value.slice(1)}`;
}

function parseDeclarations(source: string): Declaration[] {
  const lines = source.split(/\r?\n/);
  const declarations: Declaration[] = [];
  for (let index = 0; index < lines.length; index += 1) {
    const match = /^\s*val\s+(\w+):\s*TextStyle\s*$/.exec(lines[index] ?? '');
    if (!match?.[1]) {
      continue;
    }
    const name = match[1];
    let end = index + 1;
    while (end < lines.length && !/^\s*\)\s*$/.test(lines[end] ?? '')) {
      end += 1;
    }
    const block = lines.slice(index, end + 1).join('\n');
    const fields: Record<string, string> = {};
    for (const field of block.matchAll(/(\w+)\s*=\s*([^,\n]+)/g)) {
      if (field[1] && field[2]) {
        fields[field[1]] = field[2].trim();
      }
    }
    declarations.push({ name, line: index + 1, fields });
  }
  return declarations;
}

function requireField(declaration: Declaration, field: string): string {
  const value = declaration.fields[field];
  if (!value) {
    throw new Error(`TypographyTokens.${declaration.name} is missing ${field}`);
  }
  return value;
}

const [source, specText] = await Promise.all([
  readFile(typographySourcePath, 'utf8'),
  readFile(typographySpecPath, 'utf8'),
]);
const spec = JSON.parse(specText) as TypographySpec;
const declarations = parseDeclarations(source);

if (declarations.length !== 30) {
  throw new Error(`expected 30 TypographyTokens declarations, found ${declarations.length}`);
}
if (spec.roles.length !== 30) {
  throw new Error(`expected 30 typography roles, found ${spec.roles.length}`);
}

const roles = new Map(spec.roles.map((role) => [role.role, role]));
const rows: string[] = [];
for (const [index, declaration] of declarations.entries()) {
  const role = camelCase(declaration.name);
  const record = roles.get(role);
  if (!record) {
    throw new Error(`no typography.json role for TypographyTokens.${declaration.name}`);
  }
  const expected = [
    requireField(declaration, 'fontFamily'),
    requireField(declaration, 'fontWeight'),
    requireField(declaration, 'fontSize'),
    requireField(declaration, 'lineHeight'),
    requireField(declaration, 'letterSpacing'),
  ];
  const actual = [
    `fontFamily ?: TypeScaleTokens.${declaration.name}Font`,
    `TypeScaleTokens.${declaration.name}Weight`,
    `TypeScaleTokens.${declaration.name}Size`,
    `TypeScaleTokens.${declaration.name}LineHeight`,
    `TypeScaleTokens.${declaration.name}Tracking`,
  ];
  if (expected.join('|') !== actual.join('|')) {
    throw new Error(
      `TypographyTokens.${declaration.name} no longer maps one-to-one to its TypeScaleTokens fields`,
    );
  }
  rows.push(
    `| ${index + 1} | \`TypographyTokens.${declaration.name}\` | \`TypographyTokens.kt:${declaration.line}\` | \`${role}\` | ${record.fontFamily} | ${record.fontWeight} | ${record.fontSize}sp | ${record.lineHeight}sp | ${record.letterSpacing}sp |`,
  );
}

