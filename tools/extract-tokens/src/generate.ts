function toKebabCase(value: string): string {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

function objectLabel(declarationName: string): string {
  return declarationName.endsWith('Tokens')
    ? declarationName.slice(0, -'Tokens'.length)
    : declarationName;
}

function specValue(value: ResolvedValue): { value: unknown; unit: string } {
  switch (value.kind) {
    case 'dp':
      return { value: value.value, unit: 'dp' };
    case 'sp':
      return { value: value.value, unit: 'sp' };
    case 'number':
      return { value: value.value, unit: 'number' };
    case 'color':
      return { value: value.value, unit: 'color' };
    case 'colorRole':
      return { value: value.value, unit: 'color-role' };
    case 'shapeKey':
      return { value: value.value, unit: 'shape-role' };
    case 'shape':
      return { value: value.value, unit: 'shape' };
    case 'typographyRole':
      return { value: value.value, unit: 'typography-role' };
    case 'motionKey':
      return { value: value.value, unit: 'motion-role' };
    case 'fontFamily':
      return { value: value.value, unit: 'font-family' };
    case 'fontWeight':
      return { value: value.value, unit: 'font-weight' };
    case 'cubicBezier':
      return { value: value.value, unit: 'cubic-bezier' };
    case 'cornerSize':
      return { value: value.value, unit: 'corner-size' };
    case 'enum':
      return { value: value.value, unit: 'enum' };
    case 'reference':
      return { value: value.value, unit: 'reference' };
    case 'raw':
      return { value: value.value, unit: 'raw' };
  }
}

function tokenSpec(
  token: TokenFileSpec['tokens'][number],
  resolved: ResolvedValue,
  file: TokenFileSpec,
): Record<string, unknown> {
  const { value, unit } = specValue(resolved);
  return {
    token: `${objectLabel(file.declarationName)}.${token.name}`,
    value,
    unit,
    expression: token.expression,
    source: `${file.relativePath}:${token.line}`,
    sourceVersion: `${MATERIAL3.artifact}:${MATERIAL3.version}`,
    sourceSha256: MATERIAL3.sha256,
  };
}

function serializeTs(value: unknown, indent = 0): string {
  const pad = '  '.repeat(indent);
  const innerPad = '  '.repeat(indent + 1);

  if (value === null) {
    return 'null';
  }
  if (typeof value === 'string') {
    return JSON.stringify(value);
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }
  if (Array.isArray(value)) {
    if (value.length === 0) {
      return '[]';
    }
    const items = value.map((item) => `${innerPad}${serializeTs(item, indent + 1)}`).join(',\n');
    return `[\n${items},\n${pad}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) {
      return '{}';
    }
    const body = entries
      .map(([key, item]) => `${innerPad}${JSON.stringify(key)}: ${serializeTs(item, indent + 1)}`)
      .join(',\n');
    return `{\n${body},\n${pad}}`;
  }
  throw new Error(`Cannot serialize ${typeof value}`);
}

/** The generated modules share one banner so provenance is copy-pasteable. */
function generatedHeader(): string {
  return [
    LICENSE_HEADER,
    `// Sources JAR SHA-256: ${MATERIAL3.sha256}`,
    `// Spec manifest: docs/specs/index.json`,
    '',
  ].join('\n');
}

function buildGlobalTs(model: ExtractedModel): string {
  const lines: string[] = [];
  lines.push(`export const specVersion = ${JSON.stringify(MATERIAL3.version)} as const;`);
  lines.push('');
  lines.push(`export const colorLight = ${serializeTs(model.global.colorLight)} as const;`);
  lines.push('');
  lines.push(`export const colorDark = ${serializeTs(model.global.colorDark)} as const;`);
  lines.push('');
  lines.push(`export const palette = ${serializeTs(model.global.palette)} as const;`);
  lines.push('');
  lines.push(`export const shapes = ${serializeTs(model.global.shape)} as const;`);
  lines.push('');
  lines.push(`export const cornerSizes = ${serializeTs(model.global.cornerSizes)} as const;`);
  lines.push('');
  lines.push(`export const elevation = ${serializeTs(model.global.elevation)} as const;`);
  lines.push('');
  lines.push(`export const typography = ${serializeTs(model.global.typography)} as const;`);
  lines.push('');
  lines.push(`export const motion = ${serializeTs(model.global.motion)} as const;`);
  lines.push('');
  lines.push(`export const state = ${serializeTs(model.global.state)} as const;`);
  lines.push('');
  lines.push('export type TypeScaleRole = keyof typeof typography;');
  lines.push('export type StateRole = keyof typeof state;');
  lines.push('export type ShapeName = keyof typeof shapes;');
  lines.push('export type ColorRole = keyof typeof colorLight;');
  return `${generatedHeader()}${lines.join('\n')}\n`;
}

function buildComponentsTs(model: ExtractedModel): string {
  const lines: string[] = [];
  lines.push(`export const componentTokens = ${serializeTs(model.componentTokens)} as const;`);
  lines.push('');
  lines.push('export type ComponentTokenFile = keyof typeof componentTokens;');
  lines.push('export type ComponentTokenValue = {');
  lines.push(
    '  [K in ComponentTokenFile]: (typeof componentTokens)[K][keyof (typeof componentTokens)[K]];',
  );
  lines.push('}[ComponentTokenFile];');
  return `${generatedHeader()}${lines.join('\n')}\n`;
}

function buildKeyTokensTs(model: ExtractedModel): string {
  const lines: string[] = [];
  lines.push(`export const colorSchemeKeyTokens = ${serializeTs(model.keyTokens.color)} as const;`);
  lines.push('');
  lines.push(`export const shapeKeyTokens = ${serializeTs(model.keyTokens.shape)} as const;`);
  lines.push('');
  lines.push(
    `export const typographyKeyTokens = ${serializeTs(model.keyTokens.typography)} as const;`,
  );
  lines.push('');
  lines.push(
    `export const motionSchemeKeyTokens = ${serializeTs(model.keyTokens.motion)} as const;`,
  );
  lines.push('');
  lines.push('export type ColorSchemeKeyToken = (typeof colorSchemeKeyTokens)[number];');
  lines.push('export type ShapeKeyToken = (typeof shapeKeyTokens)[number];');
  lines.push('export type TypographyKeyToken = (typeof typographyKeyTokens)[number];');
  lines.push('export type MotionSchemeKeyToken = (typeof motionSchemeKeyTokens)[number];');
  return `${generatedHeader()}${lines.join('\n')}\n`;
}

async function format(
  source: string,
  filePath: string,
  parser: 'typescript' | 'json',
): Promise<string> {
  const config = (await prettier.resolveConfig(filePath)) ?? {};
  return prettier.format(source, { ...config, parser });
}

function globalRecords(model: ExtractedModel): Record<string, Record<string, unknown>[]> {
  const groups: Record<string, Record<string, unknown>[]> = {};
  for (const file of model.files) {
    if (!GLOBAL_SET.has(file.declarationName)) {
      continue;
    }
    const resolved = model.allTokens[file.declarationName];
    if (!resolved) {
      throw new Error(`missing resolved tokens for ${file.declarationName}`);
    }
    groups[file.declarationName] = file.tokens.map((token) =>
      tokenSpec(token, resolved[token.name] ?? { kind: 'raw', value: token.expression }, file),
    );
  }
  return groups;
}

function typographyRecords(model: ExtractedModel): Record<string, unknown>[] {
  const typeScale = model.files.find((file) => file.declarationName === 'TypeScaleTokens');
  if (!typeScale) {
    throw new Error('TypeScaleTokens not found');
  }
  const byName = new Map(typeScale.tokens.map((token) => [token.name, token]));

  return Object.entries(model.global.typography).map(([role, style]) => {
    const pascal = `${role[0]?.toUpperCase() ?? ''}${role.slice(1)}`;
    const sourceFor = (suffix: string): string => {
      const token = byName.get(`${pascal}${suffix}`);
      if (!token) {
        throw new Error(`missing TypeScaleTokens.${pascal}${suffix}`);
      }
      return `${typeScale.relativePath}:${token.line}`;
    };
    return {
      role,
      ...style,
      sources: {
        fontFamily: sourceFor('Font'),
        fontWeight: sourceFor('Weight'),
        fontSize: sourceFor('Size'),
        lineHeight: sourceFor('LineHeight'),
        letterSpacing: sourceFor('Tracking'),
      },
      sourceVersion: `${MATERIAL3.artifact}:${MATERIAL3.version}`,
      sourceSha256: MATERIAL3.sha256,
    };
  });
}

function assertNoCollisions(fileNames: string[]): void {
  const seen = new Map<string, string>();
  for (const fileName of fileNames) {
    const previous = seen.get(fileName);
    if (previous) {
      throw new Error(`spec filename collision: ${previous} and ${fileName}`);
    }
    seen.set(fileName, fileName);
  }
}

interface OutputSet {
  specDir: string;
  generatedDir: string;
  files: Map<string, string>;
  specFileNames: string[];
}

async function buildOutputs({ root, model }: EmitOptions): Promise<OutputSet> {
  const specDir = path.join(root, 'docs/specs');
  const generatedDir = path.join(
    root,
    'packages/react-native-material-expressive/src/tokens/generated',
  );
  const files = new Map<string, string>();

  const componentNames = Object.keys(model.componentTokens).sort((a, b) => a.localeCompare(b));
  const specFileNames = componentNames.map((name) => `${toKebabCase(objectLabel(name))}.json`);
  assertNoCollisions(specFileNames);

  const meta = {
    generatedBy: 'tools/extract-tokens',
    artifact: `${MATERIAL3.artifact}:${MATERIAL3.version}`,
    jarSha256: MATERIAL3.sha256,
  };

  const add = async (
    filePath: string,
    source: string,
    parser: 'typescript' | 'json',
  ): Promise<void> => {
    files.set(filePath, await format(source, filePath, parser));
  };

  for (const [index, declarationName] of componentNames.entries()) {
    const fileName = specFileNames[index];
    if (!fileName) {
      throw new Error(`missing spec filename for ${declarationName}`);
    }
    const file = model.files.find((candidate) => candidate.declarationName === declarationName);
    if (!file) {
      throw new Error(`missing token file for ${declarationName}`);
    }
    const resolved = model.allTokens[declarationName];
    if (!resolved) {
      throw new Error(`missing resolved token map for ${declarationName}`);
    }

    const spec = {
      ...meta,
      tokenFile: file.relativePath,
      declaration: file.declarationName,
      declarationKind: file.declarationKind,
      tokenVersion: file.version,
      tokens: file.tokens.map((token) =>
        tokenSpec(token, resolved[token.name] ?? { kind: 'raw', value: token.expression }, file),
      ),
    };
    await add(path.join(specDir, fileName), `${JSON.stringify(spec, null, 2)}\n`, 'json');
  }

  await add(
    path.join(specDir, 'tokens.json'),
    `${JSON.stringify(
      {
        ...meta,
        description:
          'Primitive, semantic, shape, typography-scale, motion, state, and key tokens. One record per Compose token property.',
        groups: globalRecords(model),
      },
      null,
      2,
    )}\n`,
    'json',
  );

  await add(
    path.join(specDir, 'typography.json'),
    `${JSON.stringify(
      {
        ...meta,
        description: 'All TextStyles resolved from TypeScaleTokens + TypefaceTokens.',
        roles: typographyRecords(model),
      },
      null,
      2,
    )}\n`,
    'json',
  );

  const index = {
    ...meta,
    sources: SOURCES.map((source) => ({
      artifact: `${source.group}:${source.artifact}:${source.version}`,
      sha256: source.sha256,
    })),
    counts: model.counts,
    tokenFiles: model.files.map((file) => {
      const kind = COMPOSITE_SET.has(file.declarationName)
        ? 'composite'
        : GLOBAL_SET.has(file.declarationName)
          ? 'global'
          : 'component';
      return {
        file: objectLabel(file.declarationName),
        declaration: file.declarationName,
        kind,
        spec:
          kind === 'composite'
            ? 'typography.json'
            : kind === 'global'
              ? 'tokens.json'
              : `${toKebabCase(objectLabel(file.declarationName))}.json`,
        version: file.version,
        tokens: file.tokens.length,
      };
    }),
    totals: {
      componentSpecs: componentNames.length,
      typographyRoles: Object.keys(model.global.typography).length,
      colorRolesLight: Object.keys(model.global.colorLight).length,
      colorRolesDark: Object.keys(model.global.colorDark).length,
    },
  };
  await add(path.join(specDir, 'index.json'), `${JSON.stringify(index, null, 2)}\n`, 'json');

  await add(path.join(generatedDir, 'global.ts'), buildGlobalTs(model), 'typescript');
  await add(path.join(generatedDir, 'components.ts'), buildComponentsTs(model), 'typescript');
  await add(path.join(generatedDir, 'key-tokens.ts'), buildKeyTokensTs(model), 'typescript');
  await add(
    path.join(generatedDir, 'index.ts'),
    [
      'export * from "./components";',
      'export * from "./global";',
      'export * from "./key-tokens";',
      '',
    ].join('\n'),
    'typescript',
  );

  return { specDir, generatedDir, files, specFileNames };
}

async function writeOutputs(outputs: OutputSet): Promise<void> {
  for (const [filePath, content] of outputs.files) {
    await mkdir(path.dirname(filePath), { recursive: true });
    await writeFile(filePath, content, 'utf8');
  }
}

export interface CheckResult {
  missing: string[];
  changed: string[];
  extra: string[];
}

async function listOutputFiles(outputs: OutputSet): Promise<string[]> {
  const listed: string[] = [];
  for (const [dir, extension] of [
    [outputs.specDir, '.json'],
    [outputs.generatedDir, '.ts'],
  ] as const) {
    let entries: string[];
    try {
      entries = await readdir(dir);
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (entry.endsWith(extension)) {
        listed.push(path.join(dir, entry));
      }
    }
  }
  return listed;
}

export async function emit(
  options: EmitOptions,
): Promise<{ specDir: string; generatedDir: string; files: string[] }> {
  const outputs = await buildOutputs(options);
  await writeOutputs(outputs);
  return {
    specDir: outputs.specDir,
    generatedDir: outputs.generatedDir,
    files: outputs.specFileNames,
  };
}

export async function check(options: EmitOptions): Promise<CheckResult> {
  const outputs = await buildOutputs(options);
  const missing: string[] = [];
  const changed: string[] = [];

  for (const [filePath, expected] of outputs.files) {
    const actual = await readIfExists(filePath);
    if (actual === null) {
      missing.push(filePath);
    } else if (actual !== expected) {
      changed.push(filePath);
    }
  }

  const expectedPaths = new Set(outputs.files.keys());
  const extra = (await listOutputFiles(outputs)).filter((filePath) => !expectedPaths.has(filePath));

  return { missing, changed, extra };
}

export function summarize(model: ExtractedModel): string {
  const rawTokens = model.files
    .filter((file) => file.declarationName !== 'TypographyTokens')
    .flatMap((file) =>
      file.tokens
        .filter((token) => model.allTokens[file.declarationName]?.[token.name]?.kind === 'raw')
        .map((token) => `${file.declarationName}.${token.name}`),
    );

  return [
    `token files: ${model.counts.tokenFiles}`,
    `tokens: ${model.counts.tokens}`,
    `resolved: ${model.counts.resolved}`,
    `raw: ${model.counts.raw}`,
    `composite: ${model.counts.composite}`,
    `component objects: ${Object.keys(model.componentTokens).length}`,
    `typography roles: ${Object.keys(model.global.typography).length}`,
    `color roles: ${Object.keys(model.global.colorLight).length} light / ${Object.keys(model.global.colorDark).length} dark`,
    `shapes: ${Object.keys(model.global.shape).length} + ${Object.keys(model.global.cornerSizes).length} corner sizes`,
    `raw tokens: ${rawTokens.length}${rawTokens.length > 0 ? ` (${rawTokens.slice(0, 8).join(', ')})` : ''}`,
  ].join('\n');
}

/** Used by the drift check; keeps `readFile` imports honest. */
export async function readIfExists(filePath: string): Promise<string | null> {
  try {
    return await readFile(filePath, 'utf8');
  } catch {
    return null;
  }
}
