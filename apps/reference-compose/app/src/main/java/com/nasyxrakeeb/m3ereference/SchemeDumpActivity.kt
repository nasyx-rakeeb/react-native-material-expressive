    private fun dynamicTones(): JSONObject {
        val tones = JSONObject()
        for ((palette, range) in TONE_RANGES) {
            val values = JSONObject()
            for ((tone, suffix) in TONE_RESOURCES) {
                values.put(tone.toString(), readColor("system_${range}_$suffix"))
            }
            tones.put(palette, values)
        }
        return tones
    }

    private fun readColor(name: String): String {
        val id = resources.getIdentifier(name, "color", "android")
        check(id != 0) { "Missing Android colour resource $name" }
        return hex(getColor(id))
    }

    private fun buildTonalPalette(palette: JSONObject): Any {
        val values = ArrayList<Long>(87)
        for (paletteName in listOf("neutral", "neutralVariant")) {
            for (tone in NEUTRAL_TONES) {
                values += colorLong(palette, paletteName, tone)
            }
        }
        for (paletteName in listOf("primary", "secondary", "tertiary")) {
            for (tone in ACCENT_TONES) {
                values += colorLong(palette, paletteName, tone)
            }
        }
        val constructor = TONAL_PALETTE.declaredConstructors.first { it.parameterTypes.size == 87 }
        constructor.isAccessible = true
        return constructor.newInstance(*values.map { it as Any }.toTypedArray())
    }

    private fun colorLong(palette: JSONObject, name: String, tone: Int): Long {
        val argb = if (tone in INTERMEDIATE_TONES) {
            val base = AndroidColor.parseColor(
                palette.getJSONObject(name).getString(BASE_TONE.toString()),
            )
            derivedTone(base, tone)
        } else {
            AndroidColor.parseColor(palette.getJSONObject(name).getString(tone.toString()))
        }
        return Color(argb).value.toLong()
    }

    /** Mirrors `Color.setLuminance` for the tones Compose derives from tone 40. */
    private fun derivedTone(baseArgb: Int, tone: Int): Int {
        val cam = CAM_FROM_INT.invoke(CAM_COMPANION, baseArgb)
        val hue = CAM_GET_HUE.invoke(cam) as Float
        val chroma = CAM_GET_CHROMA.invoke(cam) as Float
        return CAM_GET_INT.invoke(CAM_COMPANION, hue, chroma, tone.toFloat()) as Int
    }

    private fun hex(color: Color): String = hex(color.toArgb())

    private fun hex(argb: Int): String = String.format(Locale.US, "#%06X", argb and 0xFFFFFF)

