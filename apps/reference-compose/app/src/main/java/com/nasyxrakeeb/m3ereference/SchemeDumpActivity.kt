        )
        val CAM_COMPANION: Any = CAM_CLASS.getField("Companion").get(null)
        val CAM_FROM_INT = CAM_COMPANION.javaClass.getMethod(
            "fromInt",
            Int::class.javaPrimitiveType,
        )
        val CAM_GET_HUE = CAM_CLASS.getMethod("getHue")
        val CAM_GET_CHROMA = CAM_CLASS.getMethod("getChroma")
        val CAM_GET_INT = CAM_COMPANION.javaClass.getMethod(
