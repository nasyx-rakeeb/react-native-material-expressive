        json.put("onSecondaryContainer", hex(scheme.onSecondaryContainer))
        json.put("tertiary", hex(scheme.tertiary))
        json.put("onTertiary", hex(scheme.onTertiary))
        json.put("tertiaryContainer", hex(scheme.tertiaryContainer))
        json.put("onTertiaryContainer", hex(scheme.onTertiaryContainer))
        json.put("background", hex(scheme.background))
        json.put("onBackground", hex(scheme.onBackground))
        json.put("surface", hex(scheme.surface))
        json.put("onSurface", hex(scheme.onSurface))
        json.put("surfaceVariant", hex(scheme.surfaceVariant))
        json.put("onSurfaceVariant", hex(scheme.onSurfaceVariant))
        json.put("surfaceTint", hex(scheme.surfaceTint))
