private const val SCHEME_TAG = "M3E_SCHEME"

/**
 * Dumps Compose's colour schemes for the Day 4 colour evidence.
 *
 * Compose Material3 1.5.0 has no seed-to-scheme API. This activity therefore:
 * - dumps the public static schemes and the device dynamic scheme;
 * - reads the 13 system tones for each tonal range from `compose-palettes.json`
 *   (generated by `tools/color/generate-goldens.mjs`), derives the intermediate
 *   tones with Compose's own internal `Cam`, and maps them through the internal
 *   `dynamicLightColorScheme31` / `dynamicDarkColorScheme31` functions.
 *
 * The last step exercises Compose's role mapping and tone derivation against
 * arbitrary variant palettes without claiming that Compose has a variant API.
 */
class SchemeDumpActivity : Activity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        try {
            val dump = buildDump()
            val file = File(filesDir, "scheme-dump.json")
            file.writeText(dump.toString(2))
            Log.i(
                SCHEME_TAG,
                "M3E_SCHEME_DUMP ${file.absolutePath} bytes=${file.length()} " +
                    "api=${Build.VERSION.SDK_INT}",
            )
        } catch (error: Throwable) {
            Log.e(SCHEME_TAG, "M3E_SCHEME_DUMP_ERROR", error)
        } finally {
            finish()
        }
    }

    private fun buildDump(): JSONObject {
        val dump = JSONObject()
            .put("schema", 1)
            .put("apiLevel", Build.VERSION.SDK_INT)
            .put("device", "${Build.MANUFACTURER} ${Build.MODEL}")
            .put(
                "defaults",
                JSONObject()
                    .put("light", schemeJson(lightColorScheme()))
                    .put("dark", schemeJson(darkColorScheme()))
                    .put("expressiveLight", schemeJson(expressiveLightColorScheme())),
            )
            .put(
                "dynamic",
                JSONObject()
                    .put("light", schemeJson(dynamicLightColorScheme(this)))
                    .put("dark", schemeJson(dynamicDarkColorScheme(this)))
                    .put("tones", dynamicTones()),
            )

        val palettes = readComposePalettes()
        val mapped = JSONObject()
        for (key in palettes.keys()) {
            val palette = buildTonalPalette(palettes.getJSONObject(key))
            mapped.put(
                key,
                JSONObject()
                    .put("light", schemeJson(invoke31(LIGHT_31, palette)))
                    .put("dark", schemeJson(invoke31(DARK_31, palette))),
            )
        }
        dump.put("mapped", mapped)

        val materialJava = buildMaterialJavaSchemes()
        dump.put("materialJava", materialJava)

        Log.i(SCHEME_TAG, "M3E_SCHEME_MAPPED count=${mapped.length()}")
        Log.i(SCHEME_TAG, "M3E_SCHEME_MATERIAL_JAVA count=${materialJava.length()}")
        return dump
    }

    /**
     * Independent Java implementation of the same Material colour spec, from
     * `com.google.android.material:material:1.11.0`. This is an oracle for the
     * generated variants, which Compose 1.5.0 does not expose.
     */
    private fun buildMaterialJavaSchemes(): JSONObject {
        val result = JSONObject()
        val colors = MaterialColors()
        for (seed in SEEDS) {
            val hct = MaterialHct.fromInt(AndroidColor.parseColor(seed))
            for ((variant, constructor) in MATERIAL_SCHEMES) {
                for (contrast in CONTRAST_LEVELS) {
                    for (isDark in listOf(false, true)) {
                        val scheme = constructor(hct, isDark, contrast)
                        val roles = JSONObject()
                        for (role in M3_ROLES) {
                            val method = MATERIAL_METHODS.getValue(role)
                            val color = method.invoke(colors) as MaterialDynamicColor
                            roles.put(role, hex(color.getArgb(scheme)))
                        }
                        val key =
                            "$seed|$variant|${if (isDark) "dark" else "light"}|$contrast"
                        result.put(key, roles)
                    }
                }
            }
        }
        return result
    }

    private fun readComposePalettes(): JSONObject {
        val text = assets.open("compose-palettes.json").bufferedReader().use { it.readText() }
        return JSONObject(text).getJSONObject("palettes")
    }

    private fun invoke31(method: java.lang.reflect.Method, palette: Any): ColorScheme =
        method.invoke(null, palette) as ColorScheme

